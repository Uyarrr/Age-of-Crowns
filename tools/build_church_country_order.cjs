// Rebuild the Papal Bulls picker order from the English base country names.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const game = process.argv[2];
if (!game) throw new Error('Pass the path to Victoria 3’s game directory.');

function localizationFiles(directory) {
    return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
        const file = path.join(directory, entry.name);
        if (entry.isDirectory()) return localizationFiles(file);
        return entry.name.endsWith('.yml') ? [file] : [];
    });
}

function readNames(directory, names) {
    const files = localizationFiles(directory).sort((a, b) => {
        const isReplace = file => path.relative(directory, file).split(path.sep).includes('replace');
        return Number(isReplace(a)) - Number(isReplace(b)) || a.localeCompare(b, 'en');
    });
    for (const file of files) {
        const source = fs.readFileSync(file, 'utf8');
        for (const [, tag, name] of source.matchAll(/^\s*([A-Z0-9]{3}):(?:\d+)?[ \t]*"([^"\r\n]+)"/gm)) {
            names.set(tag, name);
        }
    }
}

const names = new Map();
readNames(path.join(game, 'localization', 'english'), names);
if (!names.size) throw new Error('No English country names found in the game directory.');
readNames(path.join(root, 'localization', 'english'), names);

const definitions = path.join(root, 'common', 'country_definitions');
const tags = new Set();
for (const file of fs.readdirSync(definitions)) {
    if (!file.endsWith('.txt') || file === '99_dynamic.txt') continue;
    const source = fs.readFileSync(path.join(definitions, file), 'utf8').replace(/^\uFEFF/, '');
    for (const [, tag] of source.matchAll(/^([A-Z0-9]{3})[ \t]*\??=[ \t]*\{/gm)) tags.add(tag);
}
tags.delete('PAP');

function nameOf(tag) {
    const name = names.get(tag) ?? tag;
    const alias = /^\$([A-Z0-9]{3})\$$/.exec(name);
    return alias ? names.get(alias[1]) ?? tag : name;
}

const collator = new Intl.Collator('en', { sensitivity: 'base' });
const ordered = [...tags].sort((a, b) => collator.compare(nameOf(a), nameOf(b)) || a.localeCompare(b));
const lines = [
    '# Generated by tools/build_church_country_order.cjs.',
    '# English base country names, in the order used by the Papal Bulls picker.',
    'aoc_church_add_debtors_by_name = {',
    ...ordered.map(tag => `\tc:${tag} ?= { aoc_church_add_relief_debtor = yes }`),
    '}',
];
fs.writeFileSync(path.join(root, 'common', 'scripted_effects', 'aoc_church_country_order.txt'),
    '\uFEFF' + lines.join('\n') + '\n');
